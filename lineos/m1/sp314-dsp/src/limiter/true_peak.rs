pub struct TruePeakDetector {
    delay_l: [f32; 18],
    delay_r: [f32; 18],
    write_pos: usize,
}

impl Default for TruePeakDetector {
    fn default() -> Self {
        Self::new()
    }
}

impl TruePeakDetector {
    pub fn new() -> Self {
        Self {
            delay_l: [0.0_f32; 18],
            delay_r: [0.0_f32; 18],
            write_pos: 0,
        }
    }

    #[inline]
    pub fn process(&mut self, left: f32, right: f32) -> f32 {
        self.delay_l[self.write_pos] = left;
        self.delay_r[self.write_pos] = right;
        
        let mut true_peak = 0.0_f32;
        
        for phase in 0..4 {
            let mut acc_l = 0.0_f64;
            let mut acc_r = 0.0_f64;
            
            for tap in 0..18 {
                let idx = (self.write_pos + 18 - tap) % 18;
                let coeff = POLYPHASE[phase][tap];
                acc_l += coeff * (self.delay_l[idx] as f64);
                acc_r += coeff * (self.delay_r[idx] as f64);
            }
            
            let interp_l = libm::fabs(acc_l) as f32;
            let interp_r = libm::fabs(acc_r) as f32;
            
            if interp_l > true_peak { true_peak = interp_l; }
            if interp_r > true_peak { true_peak = interp_r; }
        }
        
        self.write_pos = (self.write_pos + 1) % 18;
        true_peak
    }

    pub fn reset(&mut self) {
        self.delay_l = [0.0_f32; 18];
        self.delay_r = [0.0_f32; 18];
        self.write_pos = 0;
    }
}
