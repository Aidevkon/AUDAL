use sp314_dsp::masking_eq::biquad::{
    BiquadCoeffs, BiquadState, rbj_bell, rbj_low_shelf, rbj_high_shelf, rbj_highpass, rbj_lowpass, process_tdf2
};

const SAMPLE_RATE: f64 = 48000.0;
const F0: f64 = 100.0;
const Q: f64 = 0.707;
const GAIN_DB: f64 = 6.0;

fn calculate_mse(actual: &[f64], expected: &[f64]) -> f64 {
    assert_eq!(actual.len(), expected.len());
    let mut sum = 0.0;
    for i in 0..actual.len() {
        let diff = actual[i] - expected[i];
        sum += diff * diff;
    }
    sum / actual.len() as f64
}

fn check_filter(
    name: &str,
    coeffs: BiquadCoeffs,
    ref_b0: f64, ref_b1: f64, ref_b2: f64, ref_a1: f64, ref_a2: f64,
    ref_ir: &[f64; 16]
) {
    let actual_coeffs = [coeffs.b0, coeffs.b1, coeffs.b2, coeffs.a1, coeffs.a2];
    let expected_coeffs = [ref_b0, ref_b1, ref_b2, ref_a1, ref_a2];
    
    let coeff_mse = calculate_mse(&actual_coeffs, &expected_coeffs);
    println!("{} coeffs MSE: {:.15e}", name, coeff_mse);
    assert!(coeff_mse < 1e-10, "{} coeffs MSE too high: {}", name, coeff_mse);

    let mut state = BiquadState::new();
    let mut actual_ir = [0.0f64; 16];
    
    for i in 0..16 {
        let input = if i == 0 { 1.0f32 } else { 0.0f32 };
        actual_ir[i] = process_tdf2(input, &coeffs, &mut state) as f64;
    }
    
    let ir_mse = calculate_mse(&actual_ir, ref_ir);
    println!("{} IR MSE: {:.15e}", name, ir_mse);
    assert!(ir_mse < 1e-10, "{} IR MSE too high: {}", name, ir_mse);
}

